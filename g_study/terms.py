@lru_cache(maxsize=1)
def all_terms() -> list[dict]:
    return list(TERMS)


def chapters() -> list[str]:
    seen: list[str] = []
    for t in TERMS:
        if t["chapter"] not in seen:
            seen.append(t["chapter"])
    return seen


def sections_for(chapter: str) -> list[str]:
    seen: list[str] = []
    for t in TERMS:
        if t["chapter"] == chapter and t["section"] not in seen:
            seen.append(t["section"])
    return seen


def filter_terms(
    field: str | None = None,
    chapter: str | None = None,
    section: str | None = None,
    query: str | None = None,
) -> list[dict]:
    q = (query or "").strip().lower()
    out = []
    for t in TERMS:
        if field and field != "すべて" and t["field"] != field:
            continue
        if chapter and chapter != "すべて" and t["chapter"] != chapter:
            continue
        if section and section != "すべて" and t["section"] != section:
            continue
        if q:
            blob = f"{t['term']} {t['definition']} {t['exam_point']} {' '.join(t['related'])}".lower()
            if q not in blob:
                continue
        out.append(t)
    return out


def find_term(name: str) -> dict | None:
    for t in TERMS:
        if t["term"] == name:
            return t
    return None
