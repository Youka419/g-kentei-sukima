def _eq(
    term: str,
    chapter: str,
    section: str,
    field: str,
    stem: str,
    options: list[str],
    answer: str,
    exam_point: str,
) -> dict:
    found = find_term(term) or {}
    if answer not in options:
        raise ValueError(f"answer not in options: {term} / {answer}")
    return {
        "term": term,
        "field": field,
        "chapter": chapter,
        "section": section,
        "definition": found.get("definition", ""),
        "exam_point": exam_point,
        "related": found.get("related") or [],
        "pdf": found.get("pdf") or PDF_MAP.get(chapter, ""),
        "stem": stem,
        "options": list(options),
        "answer": answer,
        "kind": "exam",
    }


