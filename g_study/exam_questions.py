def filter_exam_questions(
    chapter: str | None = None,
    field: str | None = None,
    terms: list[str] | None = None,
) -> list[dict]:
    wanted = {str(x) for x in terms} if terms is not None else None
    out = []
    for q in EXAM_QUESTIONS:
        if field and field != "すべて" and q["field"] != field:
            continue
        if chapter and chapter != "すべて" and q["chapter"] != chapter:
            continue
        if wanted is not None and q["term"] not in wanted:
            continue
        out.append(q)
    return out
